const {PGlite}=require('@electric-sql/pglite'),fs=require('fs'),assert=require('assert');
const owner='11111111-1111-1111-1111-111111111111',other='22222222-2222-2222-2222-222222222222';
(async()=>{
 const db=new PGlite();
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE SCHEMA auth;CREATE SCHEMA storage;
 CREATE TABLE auth.users(id uuid PRIMARY KEY);INSERT INTO auth.users VALUES('${owner}'),('${other}');
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 CREATE TABLE storage.objects(id bigint GENERATED ALWAYS AS IDENTITY,name text,bucket_id text);
 CREATE FUNCTION storage.foldername(text) RETURNS text[] LANGUAGE sql AS $$ SELECT string_to_array($1,'/') $$;
 ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
 GRANT USAGE ON SCHEMA public,auth,storage TO authenticated,anon;
 GRANT SELECT,INSERT,UPDATE,DELETE ON storage.objects TO authenticated;GRANT USAGE ON SEQUENCE storage.objects_id_seq TO authenticated;`);
 await db.exec(fs.readFileSync('supabase/new-project-bootstrap.sql','utf8'));
 await db.exec(`SET ROLE authenticated;SET request.jwt.claim.sub='${owner}';
 INSERT INTO public.app_backups(user_id,payload) VALUES('${owner}','{"current":{"kohde":"keep"}}');
 INSERT INTO public.app_backup_versions(user_id,created_at,payload) SELECT '${owner}', '2026-10-05'::timestamptz+make_interval(mins=>g), jsonb_build_object('number',g) FROM generate_series(1,100)g;`);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM public.app_backup_versions')).rows[0].n,20);
 await db.exec(`INSERT INTO public.app_backup_versions(user_id,created_at,payload) VALUES('${owner}','2026-10-05'::timestamptz+make_interval(mins=>100),'{"number":100}') ON CONFLICT(user_id,created_at) DO NOTHING;`);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM public.app_backup_versions')).rows[0].n,20);
 await assert.rejects(db.exec(`INSERT INTO public.app_backup_versions(user_id,payload) VALUES('${owner}',jsonb_build_object('large',repeat('x',2097152)));`));
 await assert.rejects(db.exec(`UPDATE public.app_backups SET user_id='${other}';`));
 await db.exec(`INSERT INTO storage.objects(name,bucket_id) VALUES('${owner}/p/e/photo.jpg','Project-photos');`);
 await assert.rejects(db.exec(`INSERT INTO storage.objects(name,bucket_id) VALUES('${other}/p/e/photo.jpg','Project-photos');`));
 await db.exec(`SET request.jwt.claim.sub='${other}';`);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM public.app_backups')).rows[0].n,0);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM public.app_backup_versions')).rows[0].n,0);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM storage.objects')).rows[0].n,0);
 await db.exec('RESET ROLE;SET ROLE anon;');
 await assert.rejects(db.query('SELECT * FROM public.app_backups'));
 await db.exec('RESET ROLE;');
 assert.equal((await db.query('SELECT payload FROM public.app_backups')).rows[0].payload.current.kohde,'keep');
 assert.equal((await db.query("SELECT public FROM storage.buckets WHERE id='Project-photos'")).rows[0].public,false);
 await db.close();console.log('Replacement database passed: retain 20 of 100, retry deduplication, size limit, owner RLS, photo ownership, anonymous denial, current backup preserved');
})().catch(e=>{console.error(e);process.exitCode=1});
